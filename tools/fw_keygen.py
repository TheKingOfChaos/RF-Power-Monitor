"""Create the firmware signing key and its public key header.

    python tools/fw_keygen.py            field key: secret/fw_signing_key, include/fw_public_key.h
    python tools/fw_keygen.py --dev      development key: keys/dev/fw_signing_key,
                                         include/fw_dev_public_key.h (committed, public by design)
    python tools/fw_keygen.py --out DIR  both files into DIR (tests)
    --force                              replace an existing key (asks for the word REPLACE on stdin)

The key is 32 random bytes (an Ed25519 seed). The private key is never
printed. Back up secret/fw_signing_key: without it no update the devices
accept can be built, and the devices cannot change their key.
"""

import argparse
import os
import secrets
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fwtool  # noqa: E402


def header_text(pub: bytes, comment: str) -> str:
    """C header defining FW_PUBLIC_KEY for `pub`."""
    rows = []
    for i in range(0, 32, 8):
        rows.append("    " + ", ".join("0x%02x" % b for b in pub[i:i + 8]) + ",")
    return ("// %s\n// Key id (fingerprint): %s\n#pragma once\n#include <stdint.h>\n\n"
            "static const uint8_t FW_PUBLIC_KEY[32] = {\n%s\n};\n"
            % (comment, fwtool.key_fingerprint(pub), "\n".join(rows)))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dev", action="store_true", help="development key (committed to git)")
    ap.add_argument("--out", help="write fw_signing_key and fw_public_key.h into this directory")
    ap.add_argument("--force", action="store_true", help="replace an existing key")
    args = ap.parse_args(argv)
    if args.dev and args.out:
        ap.error("--dev and --out cannot be combined")

    if args.out:
        key_path = os.path.join(args.out, "fw_signing_key")
        header_path = os.path.join(args.out, "fw_public_key.h")
        comment = "Generated by tools/fw_keygen.py"
    elif args.dev:
        key_path = fwtool.DEV_KEY
        header_path = os.path.join(fwtool.ROOT, "include", "fw_dev_public_key.h")
        comment = "Public development key (keys/dev), CI and tests only. Generated by tools/fw_keygen.py --dev"
    else:
        key_path = fwtool.FIELD_KEY
        header_path = os.path.join(fwtool.ROOT, "include", "fw_public_key.h")
        comment = "Public field key. Generated by tools/fw_keygen.py"

    fwtool.fwsign_path()  # build fwsign first: a compiler failure must not leave a key without header
    replace = os.path.exists(key_path)
    if replace:
        if not args.force:
            print("%s exists; not replacing it (--force replaces it)." % key_path, file=sys.stderr)
            return 1
        print("This replaces the signing key. Devices running firmware for the old key\n"
              "cannot be updated to the new one. Type REPLACE to continue:", file=sys.stderr)
        if sys.stdin.readline().strip() != "REPLACE":
            print("Not replaced.", file=sys.stderr)
            return 1

    os.makedirs(os.path.dirname(key_path), exist_ok=True)
    seed = secrets.token_bytes(32)
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    if replace:  # confirmed --force: write beside it, then swap
        tmp = key_path + ".new"
        if os.path.exists(tmp):
            os.remove(tmp)
        with os.fdopen(os.open(tmp, flags, 0o600), "wb") as f:
            f.write(seed)
        os.replace(tmp, key_path)
    else:  # never overwrites, even if the key appeared since the check above
        try:
            fd = os.open(key_path, flags, 0o600)
        except FileExistsError:
            print("%s exists; not replacing it (--force replaces it)." % key_path, file=sys.stderr)
            return 1
        with os.fdopen(fd, "wb") as f:
            f.write(seed)

    pub = fwtool.public_key(key_path)
    os.makedirs(os.path.dirname(header_path), exist_ok=True)
    with open(header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header_text(pub, comment))
    print("Key written to %s" % key_path)
    print("Public key header: %s" % header_path)
    print("Key id (fingerprint): %s" % fwtool.key_fingerprint(pub))
    if not args.dev:
        print("Back up the key file now (password manager or offline copy). Without it no\n"
              "update the devices accept can ever be built again.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
