"""Write test/native/dhcp6_frames/frames.h from the captures made by capture.sh and the HIL spike.

Run in WSL (needs scapy): python3 scripts/dhcp6_capture/extract.py
Frames are kept byte for byte. The one exception: frames captured on the sending side
of a virtual link carry a checksum the NIC was to finish (offload); those get the
correct UDP/ICMPv6 checksum, and the frame's comment says so.
"""

import os
import sys

from scapy.all import ICMPv6ND_RA, IPv6, UDP, Ether, rdpcap

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "test", "native", "dhcp6_frames", "frames.h")
LAB_C1 = "02:00:00:00:d6:01"
LAB_C2 = "02:00:00:00:d6:02"
DEVICE = "1e:b2:cf:4e:a2:2c"


def msg_type(p):
    return bytes(p[UDP].payload)[0] if UDP in p and len(p[UDP].payload) else None


def fixed(p):
    """(bytes, note): the frame with a correct L4 checksum."""
    raw = bytes(p)
    q = Ether(raw)
    layer = UDP if UDP in q else ICMPv6ND_RA
    got = q[layer].cksum if layer is ICMPv6ND_RA else q[layer].chksum
    if layer is UDP:
        del q[UDP].chksum
    else:
        del q[ICMPv6ND_RA].cksum
    good = Ether(bytes(q))
    want = good[layer].cksum if layer is ICMPv6ND_RA else good[layer].chksum
    if got == want:
        return raw, ""
    return bytes(good), " Checksum completed (captured before offload)."


def pick(pkts, pred, what):
    for p in pkts:
        if pred(p):
            return p
    sys.exit("not found in capture: " + what)


def c_array(name, data, comment):
    lines = ["/// %s" % comment, "static const uint8_t %s[] = {" % name]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const size_t %s_LEN = sizeof(%s);" % (name, name))
    return "\n".join(lines)


def main():
    lab = rdpcap(os.path.join(HERE, "lab.pcap"))
    spike = rdpcap(os.path.join(HERE, "spike.pcap"))
    to = lambda mac, t: (lambda p: p[Ether].dst == mac and msg_type(p) == t)  # noqa: E731
    frm = lambda mac, t: (lambda p: p[Ether].src == mac and msg_type(p) == t)  # noqa: E731
    replies_c1 = [p for p in lab if to(LAB_C1, 7)(p)]
    if len(replies_c1) < 2:
        sys.exit("need a Reply to the Request and one to a Renew")
    ra = lambda mac, m: (lambda p: ICMPv6ND_RA in p and p[Ether].dst == mac and p[ICMPv6ND_RA].M == m)  # noqa: E731

    frames = [
        ("LAB_CLIENT_SOLICIT", pick(lab, frm(LAB_C1, 1), "solicit"), "dhcpcd 10.0.6 Solicit (DUID-LL of LAB_MAC_C1, IAID 1, FQDN \"lab-client\")."),
        ("LAB_CLIENT_REQUEST", pick(lab, frm(LAB_C1, 3), "request"), "dhcpcd Request for fd00:d6::100."),
        ("LAB_CLIENT_RENEW", pick(lab, frm(LAB_C1, 5), "renew"), "dhcpcd Renew at T1."),
        ("KEA_ADVERTISE", pick(lab, to(LAB_C1, 2), "advertise"), "Kea 2.4.1 Advertise to LAB_MAC_C1: fd00:d6::100, preferred 20 s, valid 40 s, T1 6, T2 12; server DUID-LL 02:00:00:00:d6:00."),
        ("KEA_REPLY_REQUEST", replies_c1[0], "Kea Reply to the Request: same lease."),
        ("KEA_REPLY_RENEW", replies_c1[1], "Kea Reply to the first Renew."),
        ("KEA_ADVERTISE_NOADDRSAVAIL", pick(lab, to(LAB_C2, 2), "noaddrsavail advertise"), "Kea Advertise to LAB_MAC_C2 while the only pool address is leased: no address, status NoAddrsAvail."),
        ("LAB_RA_MANAGED", pick(lab, ra(LAB_C1, 1), "RA with M"), "test/hil/dhcp6/send_ra.py: M flag, router lifetime 0, unicast to LAB_MAC_C1."),
        ("LAB_RA_PLAIN", pick(lab, ra(LAB_C2, 0), "RA without M"), "send_ra.py without M or O (an ordinary LAN router's flags)."),
        ("DEVICE_INFO_REQUEST", pick(spike, frm(DEVICE, 11), "device info-request"), "The device (lwIP 2.2.1 stateless DHCPv6) Information-request after an O-flag RA; no client id."),
        ("KEA_INFO_REPLY", pick(spike, to(DEVICE, 7), "kea info reply"), "Kea Reply to the device's Information-request (HIL test network, WSL mirrored)."),
    ]
    out = [
        "// Generated by scripts/dhcp6_capture/extract.py from lab.pcap (capture.sh) and spike.pcap",
        "// (test/hil/test_dhcp6_testnet.py). Do not edit; regenerate. Full Ethernet frames.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "static const uint8_t LAB_MAC_C1[6] = {0x02, 0x00, 0x00, 0x00, 0xd6, 0x01};",
        "static const uint8_t LAB_MAC_C2[6] = {0x02, 0x00, 0x00, 0x00, 0xd6, 0x02};",
        "static const uint8_t DEVICE_MAC[6] = {0x1e, 0xb2, 0xcf, 0x4e, 0xa2, 0x2c};",
        "/// fe80::1cb2:cfff:fe4e:a22c, the device's link-local address",
        "static const uint8_t DEVICE_LL[16] = {0xfe, 0x80, 0, 0, 0, 0, 0, 0, 0x1c, 0xb2, 0xcf, 0xff, 0xfe, 0x4e, 0xa2, 0x2c};",
        "",
    ]
    for name, p, comment in frames:
        data, note = fixed(p)
        out.append(c_array(name, data, comment + note))
        out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %d frames to %s" % (len(frames), os.path.normpath(OUT)))
    for name, p, _ in frames:
        print("  %-28s %4d bytes%s" % (name, len(p), fixed(p)[1]))


if __name__ == "__main__":
    main()
