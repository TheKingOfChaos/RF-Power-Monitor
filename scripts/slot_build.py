"""PlatformIO script: link the firmware for a slot behind our own boot program.

Listed twice in platformio.ini, as `pre:` and `post:`:

  pre   (before the core's builder) writes the rule for $BUILD_DIR/memmap_slot.ld,
        a copy of the core's memmap_default.ld linked at the slot, makes it the
        linker script (board_build.ldscript) and adds -D FW_SLOT=<n> from the
        option `custom_fw_slot` (0 = slot A, 1 = slot B).
  post  (after it) builds $BUILD_DIR/firmware_full.uf2 for slot A: the boot
        program (scripts/build_boot.py), the erased boot record and the slot A
        blob, and makes `upload` (also used by `pio test`) send that file.

The slot blob is signed (tools/fwtool.py, tools/fwsign): with keys/dev/fw_signing_key,
or secret/fw_signing_key when the environment variable RFPOWER_FW_KEY=field is set.

Flash layout (offsets from 0x10000000):
  0x000000  boot2 + boot program (.pio/boot/boot.bin), ends before 0xE000
  0x00E000  boot record, 2 x 4 KB
  0x010000  slot A, 0xD7000 bytes: 256-byte header, then the image
  0x0E7000  slot B, 0xD7000 bytes: same
  0x1BE000  unused, 0x1BF000 LittleFS (256 KB), 0x1FF000 EEPROM (unchanged)

The image (firmware.bin) is linked at slot + 0x100 and starts with its vector
table: no boot2, no OTA loader, no partition block of its own.
"""

import os
import re
import sys

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
except NameError:  # imported by the unit tests (test/tools), not run by SCons
    env = None

FLASH_BASE = 0x10000000
SLOT_OFFSETS = {0: 0x10000, 1: 0xE7000}
SLOT_LENGTH = 0xD7000
HEADER_SIZE = 0x100
BOOT_RECORD_OFFSET = 0xE000
BOOT_RECORD_SIZE = 0x2000
FULL_UF2 = os.path.join("$BUILD_DIR", "firmware_full.uf2")
PROJECT_DIR = (env.subst("$PROJECT_DIR") if env is not None
               else os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCRIPTS_DIR = os.path.join(PROJECT_DIR, "scripts")
BOOT_DIR = os.path.join(PROJECT_DIR, "boot")
TOOLS_DIR = os.path.join(PROJECT_DIR, "tools")

for _dir in (SCRIPTS_DIR, TOOLS_DIR):
    if _dir not in sys.path:
        sys.path.insert(0, _dir)
import build_boot  # noqa: E402
import fwtool  # noqa: E402
import uf2  # noqa: E402


def fw_slot(env):
    """The slot this environment builds for (custom_fw_slot), 0 or 1."""
    value = str(env.GetProjectOption("custom_fw_slot", "0")).strip()
    if value not in ("0", "1"):
        sys.stderr.write("slot_build: custom_fw_slot must be 0 or 1, not %r\n" % value)
        env.Exit(1)
    return int(value)


def slot_linker_script(text, slot, subs):
    """Turn the core's memmap_default.ld text into the slot's linker script.

    subs: the core's placeholders (__FS_START__, ...) and their values.
    FLASH starts at slot + 0x100 with the slot's length less the header;
    .boot2 (and its size check), .ota and .partition are removed, so the
    image starts with .text (the vector table). Raises ValueError when the
    core's script does not look as expected (e.g. after a core update).
    """
    origin = FLASH_BASE + SLOT_OFFSETS[slot] + HEADER_SIZE
    edits = [
        (r"FLASH\(rx\) : ORIGIN = 0x10000000, LENGTH = __FLASH_LENGTH__",
         "FLASH(rx) : ORIGIN = 0x%08X, LENGTH = 0x%X" % (origin, SLOT_LENGTH - HEADER_SIZE)),
        (r"\n[ \t]*\.boot2 : \{[^}]*\} > FLASH\n", "\n"),
        (r"\n[ \t]*ASSERT\(__boot2_end__[^;]*?\"\)\n", "\n"),
        (r"\n[ \t]*\.ota : \{[^}]*\} > FLASH\n", "\n"),
        (r"\n[ \t]*\.partition : \{[^}]*\} > FLASH\n", "\n"),
    ]
    for pattern, replacement in edits:
        text, count = re.subn(pattern, replacement, text)
        if count != 1:
            raise ValueError("memmap_default.ld: %r matched %d times, expected once" % (pattern, count))
    # Nothing may still place the core's boot2 or OTA loader in the image
    marker = "SECTIONS\n{\n"
    if text.count(marker) != 1:
        raise ValueError("memmap_default.ld: %r found %d times, expected once" % (marker, text.count(marker)))
    text = text.replace(marker, marker + "    /DISCARD/ : { *(.boot2) *(.OTA) }\n\n")
    for name, value in subs.items():
        text = text.replace(name, value)
    left = re.search(r"__(FLASH_LENGTH|EEPROM_START|FS_START|FS_END|RAM_LENGTH|PSRAM_LENGTH)__", text)
    if left:
        raise ValueError("memmap_slot.ld: placeholder %s left" % left.group(0))
    header = "/* Generated by scripts/slot_build.py for slot %s from the core's memmap_default.ld */\n" % "AB"[slot]
    return header + text


def generate_linker_script(target, source, env):
    """SCons action: write memmap_slot.ld (target) from memmap_default.ld (source[0])."""
    env["__fetch_fs_size"](env)  # FS_START, FS_END, PICO_EEPROM_START (platform main.py)
    board = env.BoardConfig()
    subs = {
        "__EEPROM_START__": str(env["PICO_EEPROM_START"]),
        "__FS_START__": str(env["FS_START"]),
        "__FS_END__": str(env["FS_END"]),
        "__RAM_LENGTH__": "%dk" % (int(board.get("upload.maximum_ram_size")) // 1024),
        "__PSRAM_LENGTH__": str(int(board.get("upload.psram_length", "0"))),
    }
    with open(source[0].get_abspath(), "r", encoding="utf-8") as f:
        text = f.read()
    try:
        text = slot_linker_script(text, fw_slot(env), subs)
    except ValueError as e:
        sys.stderr.write("slot_build: %s\n" % e)
        return 1
    with open(target[0].get_abspath(), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return None


def field_key():
    """True when RFPOWER_FW_KEY=field: sign with secret/fw_signing_key, not the development key."""
    return os.environ.get("RFPOWER_FW_KEY", "") == "field"


# The boot program verifies a slot at ~2.6 us per byte (measured 2026-11-06:
# 943 ms for 359 KB, mostly SHA-512), so its 1.5 s boot budget runs out near
# 570 KB of firmware: warn from 550 KB (TODO.md)
VERIFY_WARN_BYTES = 550 * 1024
VERIFY_US_PER_BYTE = 2.6


def verify_time_warning(blob_len):
    """A warning when the boot program's check of a `blob_len` byte slot nears 1.5 s, else None."""
    if blob_len <= VERIFY_WARN_BYTES:
        return None
    return ("warning: slot A is %d KB; the boot program needs about %.1f s to verify it "
            "(budget 1.5 s, warning from %d KB)"
            % (blob_len // 1024, blob_len * VERIFY_US_PER_BYTE / 1e6, VERIFY_WARN_BYTES // 1024))


def slot_blob(env):
    """The bytes that go at the start of the slot: signed header + firmware.bin.

    Signed with the development key (keys/dev), or the field key under
    RFPOWER_FW_KEY=field. Raises ValueError when the blob does not fit the
    slot, RuntimeError when signing fails (or the field key is missing).
    """
    image_path = env.subst(os.path.join("$BUILD_DIR", "${PROGNAME}.bin"))
    seed = fwtool.signing_seed(field_key())
    blob = fwtool.sign_slot(seed, fw_slot(env), fwtool.firmware_version(), image_path)
    if len(blob) > SLOT_LENGTH:
        raise ValueError("firmware is %d bytes, the slot holds %d" % (len(blob), SLOT_LENGTH))
    return blob


def boot_program(env):
    """Build (if needed) and return the boot program, boot2 included.

    Built for the same key as the firmware (RFPOWER_FW_KEY, field_key()).
    """
    platform = env.PioPlatform()
    return build_boot.build(
        toolchain_dir=platform.get_package_dir("toolchain-rp2040-earlephilhower"),
        framework_dir=platform.get_package_dir("framework-arduinopico"),
        boot2=env.BoardConfig().get("build.arduino.earlephilhower.boot2_source",
                                    build_boot.DEFAULT_BOOT2),
        field_key=field_key())


def check_boot_trusts_key(boot, public_key):
    """Raise ValueError unless the boot program (bytes) holds `public_key`.

    The boot program verifies slots with the FW_PUBLIC_KEY it was compiled
    with; a slot signed with any other key would never start.
    """
    if len(public_key) != 32 or public_key not in boot:
        raise ValueError("the boot program does not trust the key slot A is signed with "
                         "(key id %s); rebuild with the same RFPOWER_FW_KEY"
                         % fwtool.key_fingerprint(public_key))


def build_full_uf2(target, source, env):
    """SCons action: write firmware_full.uf2 (boot program, boot record, slot A)."""
    try:
        with open(boot_program(env), "rb") as f:
            boot = f.read()
        blob = slot_blob(env)
        check_boot_trusts_key(boot, fwtool.public_key(fwtool.signing_seed(field_key())))
    except (RuntimeError, ValueError, OSError) as e:
        sys.stderr.write("slot_build: %s\n" % e)
        return 1
    uf2.write_uf2(target[0].get_abspath(), [
        (FLASH_BASE, boot),
        (FLASH_BASE + BOOT_RECORD_OFFSET, b"\xff" * BOOT_RECORD_SIZE),
        (FLASH_BASE + SLOT_OFFSETS[0], blob),
    ])
    print("firmware_full.uf2: boot program %d bytes, slot A %d of %d bytes"
          % (len(boot), len(blob), SLOT_LENGTH))
    warning = verify_time_warning(len(blob))
    if warning:
        sys.stderr.write("slot_build: %s\n" % warning)
    return None


def refuse_upload(message):
    """An SCons action that fails the upload with `message`."""
    def action(target, source, env):
        sys.stderr.write("slot_build: %s\n" % message)
        return 1
    return action


def configure_pre(env):
    """Before the core's builder: slot define and the slot's linker script."""
    slot = fw_slot(env)
    env.Append(CPPDEFINES=[("FW_SLOT", slot)])
    if field_key():
        env.Append(CPPDEFINES=["RFPOWER_FW_FIELD_KEY"])  # include/fw_key.h trusts the field key
    ldscript = os.path.join(env.subst("$BUILD_DIR"), "memmap_slot.ld")
    # The core only generates its own script when build.ldscript is empty;
    # PlatformIO read board_build.ldscript before this script ran
    env.BoardConfig().update("build.ldscript", ldscript)
    env.Replace(LDSCRIPT_PATH=ldscript)
    framework = env.PioPlatform().get_package_dir("framework-arduinopico")
    env.Command(
        ldscript,
        [os.path.join(framework, "lib", "rp2040", "memmap_default.ld"),
         env.Value("slot %d" % slot),
         os.path.join(SCRIPTS_DIR, "slot_build.py")],
        env.VerboseAction(generate_linker_script, "Generating linker script $TARGET"))


def configure_post(env):
    """After the core's builder: firmware_full.uf2 and the upload command."""
    # PROGNAME ("firmware") is only set by the platform's builder
    env.Depends(os.path.join("$BUILD_DIR", "${PROGNAME}.elf"),
                os.path.join("$BUILD_DIR", "memmap_slot.ld"))
    try:
        key_id = fwtool.key_fingerprint(fwtool.public_key(fwtool.signing_seed(field_key())))
    except RuntimeError as e:
        sys.stderr.write("slot_build: %s\n" % e)
        env.Exit(1)
    if fw_slot(env) != 0:
        env.AddPreAction("upload", refuse_upload(
            "the boot program starts slot A only; upload the pico environment "
            "(slot B images are installed by a firmware update)"))
        return
    protocol = env.subst("$UPLOAD_PROTOCOL") or "picotool"
    if protocol != "picotool":
        env.AddPreAction("upload", refuse_upload(
            "upload_protocol %s would write the bare image; only picotool "
            "(which loads firmware_full.uf2) is supported" % protocol))
    # Sources, headers (the key headers included) and linker script of the boot
    # program; boot2 is covered by the boot2_source value below
    boot_inputs = (build_boot.project_inputs()
                   + [os.path.join(SCRIPTS_DIR, n) for n in ("uf2.py", "slot_build.py")])
    full = env.Command(
        FULL_UF2,
        [os.path.join("$BUILD_DIR", "${PROGNAME}.bin"),
         env.Value(env.BoardConfig().get("build.arduino.earlephilhower.boot2_source", "")),
         env.Value("field key" if field_key() else "development key"),
         env.Value(key_id),  # a new key re-signs (the key file itself stays out of SCons)
         os.path.join(TOOLS_DIR, "fwtool.py")]
        + boot_inputs,
        env.VerboseAction(build_full_uf2, "Building $TARGET"))
    env.Alias("buildprog", full)
    env.Depends(env.Alias("upload"), full)
    # picotool (the board's protocol) loads the UF2 at its own addresses
    env.Replace(UPLOADCMD='"$UPLOADER" load $UPLOADERFLAGS "%s"' % env.subst(FULL_UF2))


if env is None:
    pass  # imported for its pure functions
elif "SLOT_BUILD_PRE_DONE" not in env:
    env["SLOT_BUILD_PRE_DONE"] = True
    configure_pre(env)
else:
    configure_post(env)
