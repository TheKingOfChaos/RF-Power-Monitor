#pragma once

/**
 * @file snmp_trap.h
 * @brief SNMPv1 Trap-PDU encoding (RFC 1157 4.1.6) and the device's traps.
 *
 *   Trap-PDU ::= [4] IMPLICIT SEQUENCE {
 *       enterprise OBJECT IDENTIFIER, agent-addr NetworkAddress,
 *       generic-trap INTEGER, specific-trap INTEGER,
 *       time-stamp TimeTicks, variable-bindings VarBindList }
 *
 * Traps sent by the device (see mibs/RF-POWER-MONITOR-MIB.txt):
 *   coldStart              generic 0, at boot once the network is up
 *   authenticationFailure  generic 4, request with a wrong community
 *   mainsPowerLost         enterpriseSpecific (6), specific 1
 *   mainsPowerRestored     enterpriseSpecific (6), specific 2
 *   mainsPowerLostTooLong  enterpriseSpecific (6), specific 3
 *   firmwareUpdateKept     enterpriseSpecific (6), specific 4
 *   firmwareRolledBack     enterpriseSpecific (6), specific 5
 * The mains traps carry mainsPowerStatus, mainsPowerChanges and
 * mainsPowerLastChange; the firmware traps fwRunningSlot, fwSlotAVersion,
 * fwSlotBVersion and fwLastResult.
 *
 * Pure C++, unit tested on the host against traps generated by net-snmp.
 */

#include "snmp_mib.h"

/// Standard SNMP trap port
constexpr uint16_t SNMP_TRAP_PORT = 162;

/// Most variable bindings in a trap
constexpr uint8_t SNMP_TRAP_MAX_VARBINDS = 4;

/// generic-trap values (RFC 1157)
enum class SnmpGenericTrap : int32_t {
    ColdStart = 0,
    WarmStart = 1,
    LinkDown = 2,
    LinkUp = 3,
    AuthenticationFailure = 4,
    EgpNeighborLoss = 5,
    EnterpriseSpecific = 6
};

/// specific-trap values for EnterpriseSpecific traps of this device
enum class MainsTrap : int32_t {
    PowerLost = 1,
    PowerRestored = 2,
    PowerLostTooLong = 3   ///< mainsPowerLostTooLong: lost for 60 s (mainsPowerAlarm raised)
};

/// specific-trap values of the firmware update traps (63050.0.4 and .0.5)
enum class FwTrap : int32_t {
    Kept = 4,        ///< firmwareUpdateKept: a new firmware was confirmed and kept
    RolledBack = 5   ///< firmwareRolledBack: the update went back to the old firmware, or a crash fell back
};

/**
 * @brief Fields of one trap
 */
struct SnmpTrap {
    const char* community;
    Oid enterprise;
    uint8_t agentAddr[4];
    SnmpGenericTrap generic;
    int32_t specific;
    uint32_t timestamp;          ///< sysUpTime when the event happened
    uint8_t varbindCount;
    Oid names[SNMP_TRAP_MAX_VARBINDS];
    SnmpValue values[SNMP_TRAP_MAX_VARBINDS];
};

/**
 * @brief Encode a trap message
 * @return Message length, or 0 if it does not fit or the trap is invalid
 */
size_t snmpBuildTrap(const SnmpTrap& trap, uint8_t* out, size_t capacity);

/**
 * @brief Encode coldStart (enterprise = sysObjectID)
 */
size_t snmpBuildColdStartTrap(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                              uint8_t* out, size_t capacity);

/**
 * @brief Encode authenticationFailure (enterprise = sysObjectID)
 */
size_t snmpBuildAuthFailureTrap(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                                uint8_t* out, size_t capacity);

/**
 * @brief Encode mainsPowerLost or mainsPowerRestored, chosen by state.mainsPresent
 *
 * time-stamp is state.mainsLastChangeTicks, the moment of the change.
 */
size_t snmpBuildMainsTrap(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                          uint8_t* out, size_t capacity);

/**
 * @brief Encode mainsPowerLostTooLong (specific-trap 3): mains has been lost for 60 s
 *
 * Varbinds as the mains traps plus mainsPowerAlarm; time-stamp is state.mainsLastChangeTicks, when
 * mains was lost.
 */
size_t snmpBuildMainsAlarmTrap(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                               uint8_t* out, size_t capacity);

/**
 * @brief Encode firmwareUpdateKept (state.fw.lastResult 1, installed) or firmwareRolledBack (any other result)
 *
 * Varbinds fwRunningSlot, fwSlotAVersion, fwSlotBVersion, fwLastResult; time-stamp is state.uptimeTicks.
 * @return 0 (nothing built) for lastResult none (0): no update happened, so there is no trap
 */
size_t snmpBuildFirmwareTrap(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                             uint8_t* out, size_t capacity);

// ---- SNMPv2-Trap (v2c, RFC 3416 4.2.6) ----
//
// SNMPv2-Trap-PDU ::= [7] { request-id, 0, 0, VarBindList }, where the list
// starts with sysUpTime.0 and snmpTrapOID.0. Trap OIDs (RFC 3418 / RFC 3584):
//   coldStart              1.3.6.1.6.3.1.1.5.1
//   authenticationFailure  1.3.6.1.6.3.1.1.5.5
//   mainsPowerLost         1.3.6.1.4.1.63050.0.1
//   mainsPowerRestored     1.3.6.1.4.1.63050.0.2
//   mainsPowerLostTooLong  1.3.6.1.4.1.63050.0.3
//   firmwareUpdateKept     1.3.6.1.4.1.63050.0.4
//   firmwareRolledBack     1.3.6.1.4.1.63050.0.5
// Every v2c trap ends with snmpTrapAddress.0 (1.3.6.1.6.3.18.1.3.0, RFC 3584), the
// device's IPv4 address, as the v1 agent-addr: a manager behind NAT (e.g. LibreNMS in
// Docker Desktop) sees another sender address and can find the device by this one.
// It is left out while the device has no IPv4 address (agentAddr 0.0.0.0).

/**
 * @brief Encode a v2c coldStart trap
 * @param agentAddr The device's IPv4 address for snmpTrapAddress.0; 0.0.0.0 leaves it out
 * @param requestId Any value; unique per trap helps managers spot duplicates
 */
size_t snmpBuildColdStartTrapV2c(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                                 int32_t requestId, uint8_t* out, size_t capacity);

/**
 * @brief Encode a v2c authenticationFailure trap
 */
size_t snmpBuildAuthFailureTrapV2c(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                                   int32_t requestId, uint8_t* out, size_t capacity);

/**
 * @brief Encode a v2c mainsPowerLost / mainsPowerRestored trap, chosen by state.mainsPresent
 *
 * sysUpTime.0 is state.mainsLastChangeTicks, the moment of the change, as the
 * v1 time-stamp. The mains objects follow snmpTrapOID.0, then snmpTrapAddress.0.
 */
size_t snmpBuildMainsTrapV2c(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                             int32_t requestId, uint8_t* out, size_t capacity);

/**
 * @brief Encode a v2c mainsPowerLostTooLong trap: as the mains traps, with mainsPowerAlarm after
 *        mainsPowerLastChange
 */
size_t snmpBuildMainsAlarmTrapV2c(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                                  int32_t requestId, uint8_t* out, size_t capacity);

/**
 * @brief Encode a v2c firmwareUpdateKept / firmwareRolledBack trap, chosen as snmpBuildFirmwareTrap();
 *        sysUpTime.0 is state.uptimeTicks
 */
size_t snmpBuildFirmwareTrapV2c(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                                int32_t requestId, uint8_t* out, size_t capacity);

/**
 * @brief What decides whether a held trap (mainsPowerLostTooLong) can leave now
 */
struct TrapPath {
    bool agentStarted;   ///< UDP socket bound
    bool linkUp;         ///< Ethernet link (W5500 PHY)
    bool hasIPv4;        ///< The network is up with an IPv4 address (not the address of a lost lease)
    bool hasIPv6;        ///< A valid global or ULA IPv6 address
    bool targetKnown;    ///< A trap destination is set (or came from DHCP)
    bool targetIPv6;     ///< That destination is IPv6 (v2c only)
};

/**
 * @brief Whether a trap sent now can reach its destination: agent, link and destination, and an own
 *        address of the destination's family. An IPv6 destination does not need IPv4 (v2c traps leave
 *        out snmpTrapAddress.0 then)
 */
bool trapCanLeave(const TrapPath& p);

/// A firmware trap leaves this long after the network came up, so coldStart (sent when the network first
/// comes up) is out first: lwIP holds one packet per unresolved ARP entry (ARP_QUEUEING 0) and a second
/// packet to the same destination would replace it
constexpr uint32_t FW_TRAP_SETTLE_MS = 2000;
/// A firmware trap whose send failed is tried again no sooner than this
constexpr uint32_t FW_TRAP_RETRY_MS = 10000;

/// What decides when a pending firmware trap is sent
struct FwTrapTiming {
    bool networkUp;          ///< snmpNetworkUp() was called and the network has not gone down since
    uint32_t networkUpMs;    ///< millis() at that call (where coldStart is sent, the first time)
    bool attempted;          ///< a send was tried since the network came up
    uint32_t lastAttemptMs;  ///< millis() of the last try
};

/**
 * @brief Whether the pending firmware trap may be sent now: the network is up, FW_TRAP_SETTLE_MS have passed since
 *        it came up, and the last failed try is FW_TRAP_RETRY_MS ago (wrap-around safe)
 */
bool fwTrapDue(const FwTrapTiming& t, uint32_t nowMs);

/**
 * @brief Allows at most one event per interval (wrap-around safe)
 *
 * Used so a flood of bad-community requests cannot cause a flood of traps.
 */
class TrapThrottle {
public:
    explicit TrapThrottle(uint32_t intervalMs) : _intervalMs(intervalMs) {}

    /// true if an event may be sent now; records it
    bool allow(uint32_t nowMs);

    /// Events refused since the last allowed one
    uint32_t suppressed() const { return _suppressed; }

private:
    uint32_t _intervalMs;
    bool _sentOnce = false;
    uint32_t _lastMs = 0;
    uint32_t _suppressed = 0;
};
