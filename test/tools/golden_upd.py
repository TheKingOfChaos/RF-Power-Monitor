"""Builds the golden .upd fixture used by test/native/test_fw_receiver.

Tiny dummy images signed with the development key through tools/fw_release.py
build_upd() and fwtool.sign_slot() (the same code the release uses). Ed25519
is deterministic, so the bytes are stable: test_fw_tools.py regenerates the
header and compares it with the committed copy.
Regenerate: python test/tools/golden_upd.py
"""

import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import fw_release  # noqa: E402
import fwtool  # noqa: E402

HEADER_PATH = os.path.join(ROOT, "test", "native", "test_fw_receiver", "golden_upd.h")
VERSION = "3.4.0"


def images():
    """The two dummy images: 300 and 4200 bytes of a counting pattern."""
    return (bytes((i * 7 + 3) & 0xFF for i in range(300)),
            bytes((i * 13 + 5) & 0xFF for i in range(4200)))


def build():
    """Returns (upd bytes, key id bytes)."""
    seed = fwtool.signing_seed(False)
    blobs = []
    with tempfile.TemporaryDirectory() as tmp:
        for slot, image in enumerate(images()):
            path = os.path.join(tmp, "image%d.bin" % slot)
            with open(path, "wb") as f:
                f.write(image)
            blobs.append(fwtool.sign_slot(seed, slot, VERSION, path))
    key_id = bytes.fromhex(fwtool.key_fingerprint(fwtool.public_key(seed)))
    return fw_release.build_upd(VERSION, blobs[0], blobs[1]), key_id


def array(name, data):
    """C source for `static const uint8_t name[]`."""
    lines = ["static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def header_text():
    """Text of golden_upd.h."""
    upd, key_id = build()
    return ("// Generated by test/tools/golden_upd.py (tools/fw_release.py build_upd, dev key). Do not edit.\n"
            "#pragma once\n#include <stdint.h>\n\n"
            + array("GOLDEN_KEY_ID", key_id) + "\n\n" + array("GOLDEN_UPD", upd) + "\n")


if __name__ == "__main__":
    with open(HEADER_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(header_text())
    print("wrote", HEADER_PATH)
